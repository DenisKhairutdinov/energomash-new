import type { Plugin } from 'vite'

// Короткие слова, которые не должны оставаться в конце строки: предлоги, союзы и частицы «не», «ни».
const WORDS = [
  'в',
  'во',
  'на',
  'с',
  'со',
  'к',
  'ко',
  'о',
  'об',
  'обо',
  'от',
  'ото',
  'по',
  'при',
  'за',
  'из',
  'изо',
  'до',
  'для',
  'без',
  'безо',
  'над',
  'надо',
  'под',
  'подо',
  'про',
  'через',
  'у',
  'ради',
  'между',
  'перед',
  'около',
  'после',
  'против',
  'среди',
  'кроме',
  'и',
  'а',
  'но',
  'да',
  'или',
  'либо',
  'что',
  'как',
  'чтобы',
  'если',
  'когда',
  'пока',
  'будто',
  'зато',
  'не',
  'ни',
]

// После слова идёт пробел, а за ним буква, цифра или открывающая кавычка/скобка; перед словом нет буквы, цифры и дефиса
const GLUE = new RegExp(
  `(?<![\\p{L}\\d-])(${WORDS.join('|')})[ \\t\\r\\n]+(?=[\\p{L}\\d«"“(])`,
  'giu',
)

// Куски, которые не трогаем: скрипты, стили, код, поля, комментарии и сами теги (атрибуты остаются как есть)
const SKIP =
  /(<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<pre[\s\S]*?<\/pre>|<code[\s\S]*?<\/code>|<textarea[\s\S]*?<\/textarea>|<!--[\s\S]*?-->|<[^>]+>)/giu

/** Ставит неразрывный пробел после предлогов, союзов и частиц «не», «ни», чтобы они не оставались в конце строки. */
export const glueText = (text: string): string => text.replace(GLUE, '$1 ')

/** Прогоняет текст страницы (всё после `<body>`) через `glueText` при сборке и в dev-сервере. */
export const nbspPlugin = (): Plugin => ({
  name: 'nbsp-glue',
  transformIndexHtml: {
    order: 'post',
    handler: (html) => {
      const bodyAt = html.search(/<body[\s>]/iu)

      if (bodyAt < 0) {
        return html
      }

      const body = html
        .slice(bodyAt)
        .split(SKIP)
        .map((part, index) => (index % 2 === 1 ? part : glueText(part)))
        .join('')

      return html.slice(0, bodyAt) + body
    },
  },
})
